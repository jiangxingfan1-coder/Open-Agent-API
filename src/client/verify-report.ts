/**
 * The result of `oaa verify`: a capability table for the terminal, a JSON report and a Markdown
 * report that can be pasted into a GitHub issue. Everything is scrubbed (verify-scrub.ts) before it
 * leaves the process: no keys, user or host name, home or other local paths.
 */
import os from 'node:os';
import { bi, pick, processLocale, type Locale } from '../core/locale.js';
import { clip, humanDuration, table } from './term.js';
import { makeScrubber, type ScrubContext } from './verify-scrub.js';
import { STATUS_LABEL } from './verify-catalog.js';
import type { RunOutcome } from './verify-run.js';
import type { Identity } from './verify-target.js';
import type { ScenarioResult } from './verify-harness.js';

export type ReportMeta = {
  requested: string;
  label: string;
  kind: string;
  engine: string;
  identity: Identity;
  model: string;
  timeoutMs: number;
  platform?: { os: string; release: string; arch: string; node: string };
};

export const REPORT_SCHEMA = 'oaa-verify-report/1';

export const machinePlatform = () => ({
  os: process.platform,
  release: os.release(),
  arch: process.arch,
  node: process.version,
});

const count = (results: ScenarioResult[], status: ScenarioResult['status']) =>
  results.filter((r) => r.status === status).length;

/** The JSON report before scrubbing. Texts keep both languages so the file reads the same everywhere. */
export function buildReport(outcome: RunOutcome, meta: ReportMeta) {
  const { results } = outcome;
  return {
    schema: REPORT_SCHEMA,
    recorded_at: outcome.startedAt,
    duration_ms: Date.parse(outcome.finishedAt) - Date.parse(outcome.startedAt),
    gateway: { name: 'Open Agent API', version: outcome.gatewayVersion },
    agent: {
      requested: meta.requested,
      label: meta.label,
      kind: meta.kind,
      engine: meta.engine,
      reported_name: meta.identity.name ?? null,
      reported_version: meta.identity.version ?? null,
      identity_source: meta.identity.source,
    },
    platform: meta.platform ?? machinePlatform(),
    request: {
      model: meta.model,
      scenario_timeout_ms: meta.timeoutMs,
      automatic_retry: false,
      live_cost: true,
    },
    interrupted: outcome.interrupted,
    setup_error: outcome.setupError ?? null,
    summary: {
      pass: count(results, 'pass'),
      fail: count(results, 'fail'),
      unsupported: count(results, 'unsupported'),
      skipped: count(results, 'skipped'),
    },
    agent_invocations_total: results.reduce((n, r) => n + r.agent_invocations, 0),
    scenarios: results.map((r) => ({
      id: r.id,
      key: r.key,
      title: r.title,
      status: r.status,
      elapsed_ms: r.elapsed_ms,
      agent_invocations: r.agent_invocations,
      ...(r.error ? { error: r.error } : {}),
      checks: r.checks,
      observations: r.observations,
      doc_mismatches: r.doc_mismatches,
      run_ids: r.run_ids,
    })),
  };
}
export type Report = ReturnType<typeof buildReport>;

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const seconds = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

/** One line on why a scenario did not pass: the failed checks, else the error. */
function why(s: Report['scenarios'][number], locale: Locale): string {
  const parts = [
    ...s.checks.filter((c) => !c.ok).map((c) => pick(c.name, locale)),
    ...(s.error ? [`${s.error.code}: ${pick(s.error.message, locale)}`] : []),
  ];
  return parts.join('; ');
}

/** The Markdown report (one language: `locale`). */
export function renderMarkdown(report: Report, locale: Locale = processLocale()): string {
  const t = (zh: string, en: string) => pick(bi(zh, en), locale);
  const a = report.agent;
  const reported = a.reported_version
    ? t(
        `自报：${a.reported_name ?? a.label} ${a.reported_version}`,
        `reports itself as: ${a.reported_name ?? a.label} ${a.reported_version}`,
      )
    : t('没有读到它自报的版本', 'its self-reported version could not be read');
  const sum = report.summary;
  const label = (status: ScenarioResult['status']) => pick(STATUS_LABEL[status], locale);
  const lines = [
    `# ${t('Open Agent API 智能体验证报告', 'Open Agent API agent verification report')}: ${a.label}`,
    '',
    `> ${t(
      '由 `oaa verify` 生成。已去除密钥、用户名、主机名与本机路径；发给智能体的只有固定的测试提示词。',
      'Generated by `oaa verify`. Keys, user name, host name and local paths are removed; the only prompts sent to the agent are the fixed test prompts.',
    )}`,
    '',
    `| ${t('项目', 'Item')} | ${t('内容', 'Value')} |`,
    '| --- | --- |',
    `| ${t('网关', 'Gateway')} | ${report.gateway.name} ${report.gateway.version} |`,
    `| ${t('智能体', 'Agent')} | \`${a.label}\` (${t('引擎', 'engine')} \`${a.engine}\`); ${reported} |`,
    `| ${t('模型', 'Model')} | \`${report.request.model}\` |`,
    `| ${t('系统', 'System')} | ${report.platform.os} ${report.platform.release} ${report.platform.arch}, Node ${report.platform.node} |`,
    `| ${t('记录时间', 'Recorded')} | ${report.recorded_at} (${humanDuration(report.duration_ms)}) |`,
    `| ${t('结果', 'Result')} | ${sum.pass} ${label('pass')}, ${sum.fail} ${label('fail')}, ${sum.unsupported} ${label('unsupported')}, ${sum.skipped} ${label('skipped')} |`,
    `| ${t('智能体调用', 'Agent calls')} | ${report.agent_invocations_total} (${t('每次都可能用到该智能体自己的登录与额度；不自动重试', "each may use the agent's own sign-in and quota; no automatic retry")}) |`,
    ...(report.interrupted
      ? [
          `| ${t('中断', 'Interrupted')} | ${t('是（Ctrl+C），未运行的场景记为跳过', 'yes (Ctrl+C); scenarios not run are marked skipped')} |`,
        ]
      : []),
    ...(report.setup_error
      ? [`| ${t('环境准备失败', 'Setup failed')} | ${cell(report.setup_error)} |`]
      : []),
    '',
    `## ${t('能力表', 'Capability table')}`,
    '',
    `| ${t('场景', 'Scenario')} | ${t('结果', 'Result')} | ${t('用时', 'Time')} | ${t('智能体调用', 'Agent calls')} | ${t('说明', 'Details')} |`,
    '| --- | --- | --- | --- | --- |',
    ...report.scenarios.map(
      (s) =>
        `| \`${s.key}\` ${cell(pick(s.title, locale))} | ${label(s.status)} | ${seconds(s.elapsed_ms)} | ${s.agent_invocations} | ${cell(s.status === 'pass' ? '' : why(s, locale))} |`,
    ),
  ];
  const failed = report.scenarios.filter((s) => s.status === 'fail');
  if (failed.length) {
    lines.push('', `## ${t('失败详情', 'Failure details')}`, '');
    for (const s of failed) {
      lines.push(`### \`${s.key}\` — ${pick(s.title, locale)}`, '');
      for (const c of s.checks.filter((x) => !x.ok))
        lines.push(
          `- ${pick(c.name, locale)}${c.detail !== undefined ? `: \`${cell(JSON.stringify(c.detail)).slice(0, 300)}\`` : ''}`,
        );
      if (s.error)
        lines.push(
          `- ${t('错误', 'Error')} \`${s.error.code}\`: ${cell(pick(s.error.message, locale))}`,
        );
      lines.push('');
    }
  }
  const mismatches = report.scenarios.flatMap((s) => s.doc_mismatches);
  lines.push(
    '',
    `## ${t('与文档不一致之处', 'Differences from the docs')}`,
    '',
    ...(mismatches.length
      ? mismatches.map((m) => `- ${pick(m, locale)}`)
      : [
          `- ${t('没有发现与 docs/adapters.md 写法不一致的观测。', 'No observation differs from what docs/adapters.md says.')}`,
        ]),
    '',
  );
  return lines.join('\n');
}

/** The capability table for the terminal. */
export function renderTable(report: Report, locale: Locale = processLocale()): string[] {
  const t = (zh: string, en: string) => pick(bi(zh, en), locale);
  const rows = [
    [
      t('场景', 'SCENARIO'),
      t('结果', 'RESULT'),
      t('用时', 'TIME'),
      t('调用', 'CALLS'),
      t('说明', 'NOTE'),
    ],
    ...report.scenarios.map((s) => [
      s.key,
      pick(STATUS_LABEL[s.status], locale),
      `${(s.elapsed_ms / 1000).toFixed(1)}s`,
      String(s.agent_invocations),
      s.status === 'pass' ? '' : clip(why(s, locale), 110),
    ]),
  ];
  const sum = report.summary;
  return [
    ...table(rows),
    '',
    t(
      `合计：${sum.pass} 通过，${sum.fail} 失败，${sum.unsupported} 不支持，${sum.skipped} 跳过；智能体调用 ${report.agent_invocations_total} 次`,
      `Total: ${sum.pass} pass, ${sum.fail} failed, ${sum.unsupported} unsupported, ${sum.skipped} skipped; ${report.agent_invocations_total} agent calls`,
    ),
  ];
}

/**
 * Scrubs the report and renders both files. The returned texts are the final, safe ones; `leaks`
 * is empty unless something survived scrubbing (then it has been replaced and is listed here).
 */
export function finalizeReport(
  outcome: RunOutcome,
  meta: ReportMeta,
  context: ScrubContext,
  locale: Locale = processLocale(),
) {
  const scrub = makeScrubber({
    ...context,
    secrets: [...(context.secrets ?? []), ...outcome.secrets],
  });
  const report = scrub.deep(buildReport(outcome, meta));
  const json = JSON.stringify(report, null, 2) + '\n';
  const md = scrub.text(renderMarkdown(report, locale));
  return { report, json, md, leaks: [...new Set([...scrub.leaks(json), ...scrub.leaks(md)])] };
}
